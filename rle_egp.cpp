uint8_t previous_bit;

inline void dispatch(EliasGammaPacker& egp, std::uint8_t byte, std::uint64_t& run_length)
{
    const Entry& e = table[byte];
    
    if(previous_bit == ((byte >> 7) & std::uint8_t{1}))
    {
        run_length += e.runs_length[0];

        if(e.size > 1){
            egp.pack(run_length);
            run_length = e.runs_length[e.size-1];
        }

        for(std::uint8_t i = 1; i+1 < e.size; ++i)
            egp.pack(e.runs_length[i]);
    }
    else
    {
        egp.pack(run_length);

        for(std::uint8_t i = 0; i+1 < e.size; ++i)
            egp.pack(e.runs_length[i]);

        run_length = e.runs_length[e.size-1];
    }

    previous_bit = byte & std::uint8_t{1};
}

int main(int argc, char ** args) {

    if(argc != 3)
    {
        std::cout << "Usage: rle_egp <input> <output>\n" << std::endl;
        return 1;
    }

    std::string input_filename = args[1];
    std::string output_filename = args[2];

    EliasGammaPacker egp;

    int fd = open(input_filename.c_str(), O_RDONLY);
    if (fd == -1)
        throw std::runtime_error("main : couldn't open file '" + input_filename + "'");


    std::size_t file_size = lseek(fd, 0, SEEK_END);

    void* map = mmap(nullptr, file_size, PROT_READ, MAP_PRIVATE, fd, 0);
    if (map == MAP_FAILED) {
        throw std::runtime_error("main : mmap initialization failed");
    }

    posix_madvise(map, file_size, MADV_SEQUENTIAL);

    std::uint8_t* data = static_cast<std::uint8_t*>(map);
 
    std::uint64_t run_length = 0;
    std::size_t i = 0;

    previous_bit = (data[0] >> 7) & std::uint8_t{1};

    egp.set_first_bit(previous_bit);
    egp.resize(1 << 26); //Set initial vector of bytes to 64MB

    // Process each bits
    for (; i < file_size; ++i) {
        dispatch(egp, data[i], run_length);
    }

    // Print final run
    if (run_length > 0) {
        egp.pack(run_length);
    }

    munmap(map, file_size);
    close(fd);

    egp.serialize(output_filename);

    return 0;
}
